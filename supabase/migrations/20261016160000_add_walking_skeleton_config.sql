-- Public, read-only project metadata used by the Week 1 health endpoint.
CREATE TABLE IF NOT EXISTS public.app_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.app_config ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read app config" ON public.app_config;
CREATE POLICY "Public can read app config"
    ON public.app_config FOR SELECT
    TO anon, authenticated
    USING (true);

INSERT INTO public.app_config (project_name)
SELECT 'CareerPrep AI'
WHERE NOT EXISTS (SELECT 1 FROM public.app_config);

GRANT SELECT ON public.app_config TO anon, authenticated;
