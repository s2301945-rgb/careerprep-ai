-- Sprint 2: bind application profiles to Supabase Auth and enable private resume CRUD.
-- Existing Laravel users are deliberately left unmapped. Linking is only by a verified
-- Supabase subject in the backend; matching by email would enable account takeover.

BEGIN;

ALTER TABLE careerprep.users
    ADD COLUMN IF NOT EXISTS auth_user_id UUID;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'careerprep.users'::regclass
          AND conname = 'fk_users_auth_user'
    ) THEN
        ALTER TABLE careerprep.users
            ADD CONSTRAINT fk_users_auth_user
            FOREIGN KEY (auth_user_id) REFERENCES auth.users (id) ON DELETE CASCADE;
    END IF;
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'careerprep.users'::regclass
          AND conname = 'uq_users_auth_user_id'
    ) THEN
        ALTER TABLE careerprep.users
            ADD CONSTRAINT uq_users_auth_user_id UNIQUE (auth_user_id);
    END IF;
END;
$$;

-- Laravel credentials are no longer a login authority. Unmapped legacy profiles
-- remain available for an explicit future account-linking workflow.
ALTER TABLE careerprep.users
    DROP COLUMN IF EXISTS password,
    DROP COLUMN IF EXISTS remember_token;

ALTER TABLE careerprep.resumes
    ADD COLUMN IF NOT EXISTS display_title VARCHAR(150);

UPDATE careerprep.resumes
SET display_title = LEFT(original_filename, 150)
WHERE display_title IS NULL;

ALTER TABLE careerprep.resumes
    ALTER COLUMN display_title SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'careerprep.resumes'::regclass
          AND conname = 'ck_resumes_display_title'
    ) THEN
        ALTER TABLE careerprep.resumes
            ADD CONSTRAINT ck_resumes_display_title
            CHECK (LENGTH(BTRIM(display_title)) BETWEEN 1 AND 150);
    END IF;
END;
$$;

-- This outbox has no foreign keys by design: it must retain a private storage key
-- after either a resume cascade or an Auth-user cascade deletes its source rows.
CREATE TABLE IF NOT EXISTS careerprep.storage_cleanup_tasks (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id       BIGINT NOT NULL,
    resume_id           BIGINT,
    storage_disk        VARCHAR(40) NOT NULL,
    storage_path        TEXT NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'pending',
    attempt_count       INTEGER NOT NULL DEFAULT 0,
    next_attempt_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    lease_expires_at    TIMESTAMPTZ,
    last_error_code     VARCHAR(100),
    requested_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at        TIMESTAMPTZ,
    CONSTRAINT uq_storage_cleanup_path UNIQUE (storage_disk, storage_path),
    CONSTRAINT ck_storage_cleanup_status CHECK (status IN (
        'armed', 'pending', 'processing', 'completed', 'cancelled'
    )),
    CONSTRAINT ck_storage_cleanup_attempt_count CHECK (attempt_count >= 0),
    CONSTRAINT ck_storage_cleanup_path CHECK (LENGTH(BTRIM(storage_path)) > 0),
    CONSTRAINT ck_storage_cleanup_completion CHECK (
        (status = 'completed' AND completed_at IS NOT NULL)
        OR (status <> 'completed' AND completed_at IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_storage_cleanup_due
    ON careerprep.storage_cleanup_tasks (next_attempt_at, id)
    WHERE status IN ('armed', 'pending', 'processing');

-- Capture every file key before deleting an Auth-linked application profile. The
-- SECURITY DEFINER owner can preserve keys despite the runtime role's narrow grants.
CREATE OR REPLACE FUNCTION careerprep.queue_user_resume_cleanup()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, careerprep
AS $$
BEGIN
    INSERT INTO careerprep.storage_cleanup_tasks (
        owner_user_id, resume_id, storage_disk, storage_path, status, next_attempt_at
    )
    SELECT r.user_id, r.id, r.storage_disk, r.storage_path, 'pending', NOW()
    FROM careerprep.resumes AS r
    WHERE r.user_id = OLD.id
    ON CONFLICT (storage_disk, storage_path) DO UPDATE
    SET owner_user_id = EXCLUDED.owner_user_id,
        resume_id = EXCLUDED.resume_id,
        status = CASE
            WHEN careerprep.storage_cleanup_tasks.status = 'completed' THEN 'completed'
            ELSE 'pending'
        END,
        next_attempt_at = CASE
            WHEN careerprep.storage_cleanup_tasks.status = 'completed'
                THEN careerprep.storage_cleanup_tasks.next_attempt_at
            ELSE NOW()
        END,
        completed_at = CASE
            WHEN careerprep.storage_cleanup_tasks.status = 'completed'
                THEN careerprep.storage_cleanup_tasks.completed_at
            ELSE NULL
        END,
        lease_expires_at = NULL;

    RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_users_queue_resume_cleanup ON careerprep.users;
CREATE TRIGGER trg_users_queue_resume_cleanup
    BEFORE DELETE ON careerprep.users
    FOR EACH ROW EXECUTE FUNCTION careerprep.queue_user_resume_cleanup();

REVOKE ALL ON FUNCTION careerprep.queue_user_resume_cleanup()
    FROM PUBLIC, anon, authenticated;

-- The bucket is private and rejects files outside the supported formats and size.
-- A non-Supabase PostgreSQL integration database has no Storage schema, so the
-- migration remains testable there while production Supabase config is applied.
DO $$
BEGIN
    IF to_regclass('storage.buckets') IS NOT NULL THEN
        INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
        VALUES (
            'resumes',
            'resumes',
            FALSE,
            10485760,
            ARRAY[
                'application/pdf',
                'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
            ]::TEXT[]
        )
        ON CONFLICT (id) DO UPDATE
        SET name = EXCLUDED.name,
            public = FALSE,
            file_size_limit = EXCLUDED.file_size_limit,
            allowed_mime_types = EXCLUDED.allowed_mime_types;
    END IF;
END;
$$;

-- LOGIN is added only during secure credential provisioning. The API receives no
-- migration-owner, Auth-admin, or broad Supabase Storage database credentials.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerprep_api') THEN
        CREATE ROLE careerprep_api NOLOGIN;
    END IF;
END;
$$;

GRANT USAGE ON SCHEMA careerprep TO careerprep_api;
GRANT SELECT, INSERT, UPDATE ON careerprep.users TO careerprep_api;
GRANT SELECT, INSERT, UPDATE, DELETE ON careerprep.resumes TO careerprep_api;
GRANT SELECT, INSERT, UPDATE ON careerprep.storage_cleanup_tasks TO careerprep_api;
GRANT USAGE, SELECT ON SEQUENCE careerprep.users_id_seq TO careerprep_api;
GRANT USAGE, SELECT ON SEQUENCE careerprep.resumes_id_seq TO careerprep_api;
GRANT USAGE, SELECT ON SEQUENCE careerprep.storage_cleanup_tasks_id_seq TO careerprep_api;

REVOKE ALL ON SCHEMA careerprep FROM PUBLIC, anon, authenticated;

COMMIT;
