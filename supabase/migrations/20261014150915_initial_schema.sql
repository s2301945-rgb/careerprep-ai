-- CareerPrep AI — initial PostgreSQL schema for Supabase-hosted PostgreSQL.
-- App architecture: Laravel-managed authentication + Laravel backend + PostgreSQL.
-- NOT a Supabase Auth migration. Users/passwords are managed by Laravel.
-- Execute ONCE in a NEW/EMPTY Supabase project.
-- Private 'careerprep' schema: DO NOT add to Supabase Data API exposed schemas.
-- Laravel must connect server-side with its private PostgreSQL credentials.
-- Configure Laravel pgsql search_path = 'careerprep,public'.

BEGIN;

CREATE SCHEMA careerprep;
REVOKE ALL ON SCHEMA careerprep FROM PUBLIC;
REVOKE ALL ON SCHEMA careerprep FROM anon, authenticated;

-- 1. Laravel-owned account identities. Only store securely hashed passwords.
CREATE TABLE careerprep.users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150) NOT NULL,
    email               VARCHAR(320) NOT NULL,
    email_verified_at   TIMESTAMPTZ,
    password            VARCHAR(255) NOT NULL,
    remember_token      VARCHAR(100),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_users_name_nonempty CHECK (LENGTH(BTRIM(name)) > 0),
    CONSTRAINT ck_users_email_nonempty CHECK (LENGTH(BTRIM(email)) > 0)
);
CREATE UNIQUE INDEX uq_users_email_case_insensitive ON careerprep.users (LOWER(email));

-- 2. Uploaded resumes and their extracted text.
-- Files themselves live in a PRIVATE storage bucket, not in PostgreSQL.
CREATE TABLE careerprep.resumes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL,
    original_filename   VARCHAR(255) NOT NULL,
    storage_disk        VARCHAR(40) NOT NULL DEFAULT 'supabase',
    storage_path        TEXT NOT NULL,
    mime_type           VARCHAR(120) NOT NULL,
    file_size_bytes     BIGINT NOT NULL,
    extracted_text      TEXT,
    extraction_status   VARCHAR(20) NOT NULL DEFAULT 'pending',
    extraction_error    VARCHAR(100),
    extracted_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_resumes_user FOREIGN KEY (user_id)
        REFERENCES careerprep.users (id) ON DELETE CASCADE,
    CONSTRAINT uq_resumes_id_user UNIQUE (id, user_id),
    CONSTRAINT uq_resumes_storage_path UNIQUE (storage_disk, storage_path),
    CONSTRAINT ck_resumes_filename CHECK (LENGTH(BTRIM(original_filename)) > 0),
    CONSTRAINT ck_resumes_path CHECK (LENGTH(BTRIM(storage_path)) > 0),
    CONSTRAINT ck_resumes_type CHECK (mime_type IN (
        'application/pdf',
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
    )),
    CONSTRAINT ck_resumes_size CHECK (file_size_bytes BETWEEN 1 AND 10485760),
    CONSTRAINT ck_resumes_status CHECK (extraction_status IN (
        'pending', 'processing', 'completed', 'failed'
    )),
    CONSTRAINT ck_resumes_error CHECK (extraction_error IS NULL OR LENGTH(BTRIM(extraction_error)) > 0)
);

-- 3. AI resume analysis. Detailed results are structured JSON arrays.
-- The documented rubric determines scores; do not treat AI scores as facts.
CREATE TABLE careerprep.resume_analyses (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL,
    resume_id           BIGINT NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'pending',
    overall_score       NUMERIC(5,2),
    summary             TEXT,
    strengths           JSONB NOT NULL DEFAULT '[]'::JSONB,
    weaknesses          JSONB NOT NULL DEFAULT '[]'::JSONB,
    missing_sections    JSONB NOT NULL DEFAULT '[]'::JSONB,
    recommendations     JSONB NOT NULL DEFAULT '[]'::JSONB,
    rubric_version      VARCHAR(80) NOT NULL DEFAULT 'resume-v1',
    model_provider      VARCHAR(80),
    model_name          VARCHAR(120),
    prompt_version      VARCHAR(80),
    error_code          VARCHAR(100),
    completed_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_resume_analyses_owned_resume FOREIGN KEY (resume_id, user_id)
        REFERENCES careerprep.resumes (id, user_id) ON DELETE CASCADE,
    CONSTRAINT ck_resume_analyses_status CHECK (status IN (
        'pending', 'processing', 'completed', 'failed'
    )),
    CONSTRAINT ck_resume_analyses_score CHECK (overall_score IS NULL OR overall_score BETWEEN 0 AND 100),
    CONSTRAINT ck_resume_analyses_strengths CHECK (JSONB_TYPEOF(strengths) = 'array'),
    CONSTRAINT ck_resume_analyses_weaknesses CHECK (JSONB_TYPEOF(weaknesses) = 'array'),
    CONSTRAINT ck_resume_analyses_missing_sections CHECK (JSONB_TYPEOF(missing_sections) = 'array'),
    CONSTRAINT ck_resume_analyses_recommendations CHECK (JSONB_TYPEOF(recommendations) = 'array'),
    CONSTRAINT ck_resume_analyses_rubric CHECK (LENGTH(BTRIM(rubric_version)) > 0),
    CONSTRAINT ck_resume_analyses_completed CHECK (completed_at IS NULL OR status = 'completed')
);

-- 4. Job descriptions supplied by the user.
CREATE TABLE careerprep.job_descriptions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL,
    job_title           VARCHAR(180),
    company_name        VARCHAR(180),
    description_text    TEXT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_job_descriptions_user FOREIGN KEY (user_id)
        REFERENCES careerprep.users (id) ON DELETE CASCADE,
    CONSTRAINT uq_job_descriptions_id_user UNIQUE (id, user_id),
    CONSTRAINT ck_job_description_content CHECK (LENGTH(BTRIM(description_text)) BETWEEN 1 AND 30000)
);

-- 5. Resume-to-job matching scores and comparisons.
CREATE TABLE careerprep.job_matches (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL,
    resume_id           BIGINT NOT NULL,
    job_description_id  BIGINT NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'pending',
    match_score         NUMERIC(5,2),
    matching_skills     JSONB NOT NULL DEFAULT '[]'::JSONB,
    missing_skills      JSONB NOT NULL DEFAULT '[]'::JSONB,
    recommendations     JSONB NOT NULL DEFAULT '[]'::JSONB,
    explanation         TEXT,
    rubric_version      VARCHAR(80) NOT NULL DEFAULT 'job-match-v1',
    model_provider      VARCHAR(80),
    model_name          VARCHAR(120),
    prompt_version      VARCHAR(80),
    error_code          VARCHAR(100),
    completed_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_job_matches_owned_resume FOREIGN KEY (resume_id, user_id)
        REFERENCES careerprep.resumes (id, user_id) ON DELETE CASCADE,
    CONSTRAINT fk_job_matches_owned_job FOREIGN KEY (job_description_id, user_id)
        REFERENCES careerprep.job_descriptions (id, user_id) ON DELETE CASCADE,
    CONSTRAINT ck_job_matches_status CHECK (status IN (
        'pending', 'processing', 'completed', 'failed'
    )),
    CONSTRAINT ck_job_matches_score CHECK (match_score IS NULL OR match_score BETWEEN 0 AND 100),
    CONSTRAINT ck_job_matches_matching_skills CHECK (JSONB_TYPEOF(matching_skills) = 'array'),
    CONSTRAINT ck_job_matches_missing_skills CHECK (JSONB_TYPEOF(missing_skills) = 'array'),
    CONSTRAINT ck_job_matches_recommendations CHECK (JSONB_TYPEOF(recommendations) = 'array'),
    CONSTRAINT ck_job_matches_rubric CHECK (LENGTH(BTRIM(rubric_version)) > 0),
    CONSTRAINT ck_job_matches_completed CHECK (completed_at IS NULL OR status = 'completed')
);

-- 6. Practice interview sessions and summary feedback.
CREATE TABLE careerprep.interview_sessions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL,
    resume_id           BIGINT NOT NULL,
    job_description_id  BIGINT,
    status              VARCHAR(20) NOT NULL DEFAULT 'pending',
    question_count      SMALLINT NOT NULL DEFAULT 5,
    overall_score       NUMERIC(5,2),
    summary             TEXT,
    strengths           JSONB NOT NULL DEFAULT '[]'::JSONB,
    improvements        JSONB NOT NULL DEFAULT '[]'::JSONB,
    rubric_version      VARCHAR(80) NOT NULL DEFAULT 'interview-v1',
    started_at          TIMESTAMPTZ,
    completed_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_interview_sessions_owned_resume FOREIGN KEY (resume_id, user_id)
        REFERENCES careerprep.resumes (id, user_id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_sessions_owned_job FOREIGN KEY (job_description_id, user_id)
        REFERENCES careerprep.job_descriptions (id, user_id) ON DELETE CASCADE,
    CONSTRAINT uq_interview_sessions_id_user UNIQUE (id, user_id),
    CONSTRAINT ck_interview_sessions_status CHECK (status IN (
        'pending', 'in_progress', 'completed', 'abandoned', 'failed'
    )),
    CONSTRAINT ck_interview_sessions_question_count CHECK (question_count BETWEEN 1 AND 20),
    CONSTRAINT ck_interview_sessions_score CHECK (overall_score IS NULL OR overall_score BETWEEN 0 AND 100),
    CONSTRAINT ck_interview_sessions_strengths CHECK (JSONB_TYPEOF(strengths) = 'array'),
    CONSTRAINT ck_interview_sessions_improvements CHECK (JSONB_TYPEOF(improvements) = 'array'),
    CONSTRAINT ck_interview_sessions_rubric CHECK (LENGTH(BTRIM(rubric_version)) > 0),
    CONSTRAINT ck_interview_sessions_completed CHECK (completed_at IS NULL OR status = 'completed')
);

-- 7. AI-generated interview questions in a stable display order.
CREATE TABLE careerprep.interview_questions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_session_id BIGINT NOT NULL,
    question_number     SMALLINT NOT NULL,
    question_type       VARCHAR(20) NOT NULL DEFAULT 'general',
    question_text       TEXT NOT NULL,
    model_provider      VARCHAR(80),
    model_name          VARCHAR(120),
    prompt_version      VARCHAR(80),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_interview_questions_session FOREIGN KEY (interview_session_id)
        REFERENCES careerprep.interview_sessions (id) ON DELETE CASCADE,
    CONSTRAINT uq_interview_questions_number UNIQUE (interview_session_id, question_number),
    CONSTRAINT ck_interview_questions_number CHECK (question_number BETWEEN 1 AND 20),
    CONSTRAINT ck_interview_questions_type CHECK (question_type IN (
        'general', 'technical', 'behavioral', 'situational'
    )),
    CONSTRAINT ck_interview_questions_content CHECK (LENGTH(BTRIM(question_text)) BETWEEN 1 AND 10000)
);

-- 8. User answer + evaluation (one current answer per question).
-- Store separate rubric component scores to make the feedback explainable.
CREATE TABLE careerprep.interview_answers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_question_id BIGINT NOT NULL UNIQUE,
    answer_text         TEXT NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'submitted',
    relevance_score     NUMERIC(5,2),
    clarity_score       NUMERIC(5,2),
    completeness_score  NUMERIC(5,2),
    examples_score      NUMERIC(5,2),
    technical_score     NUMERIC(5,2),
    overall_score       NUMERIC(5,2),
    feedback            TEXT,
    strengths           JSONB NOT NULL DEFAULT '[]'::JSONB,
    suggestions         JSONB NOT NULL DEFAULT '[]'::JSONB,
    model_provider      VARCHAR(80),
    model_name          VARCHAR(120),
    prompt_version      VARCHAR(80),
    error_code          VARCHAR(100),
    submitted_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    evaluated_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_interview_answers_question FOREIGN KEY (interview_question_id)
        REFERENCES careerprep.interview_questions (id) ON DELETE CASCADE,
    CONSTRAINT ck_interview_answers_content CHECK (LENGTH(BTRIM(answer_text)) BETWEEN 1 AND 30000),
    CONSTRAINT ck_interview_answers_status CHECK (status IN (
        'submitted', 'evaluating', 'evaluated', 'failed'
    )),
    CONSTRAINT ck_interview_answers_relevance CHECK (relevance_score IS NULL OR relevance_score BETWEEN 0 AND 100),
    CONSTRAINT ck_interview_answers_clarity CHECK (clarity_score IS NULL OR clarity_score BETWEEN 0 AND 100),
    CONSTRAINT ck_interview_answers_completeness CHECK (completeness_score IS NULL OR completeness_score BETWEEN 0 AND 100),
    CONSTRAINT ck_interview_answers_examples CHECK (examples_score IS NULL OR examples_score BETWEEN 0 AND 100),
    CONSTRAINT ck_interview_answers_technical CHECK (technical_score IS NULL OR technical_score BETWEEN 0 AND 100),
    CONSTRAINT ck_interview_answers_overall CHECK (overall_score IS NULL OR overall_score BETWEEN 0 AND 100),
    CONSTRAINT ck_interview_answers_strengths CHECK (JSONB_TYPEOF(strengths) = 'array'),
    CONSTRAINT ck_interview_answers_suggestions CHECK (JSONB_TYPEOF(suggestions) = 'array'),
    CONSTRAINT ck_interview_answers_evaluated CHECK (evaluated_at IS NULL OR status = 'evaluated')
);

-- Query indexes used by the dashboard/history pages.
CREATE INDEX idx_resumes_user_created ON careerprep.resumes (user_id, created_at DESC);
CREATE INDEX idx_resume_analyses_user_created ON careerprep.resume_analyses (user_id, created_at DESC);
CREATE INDEX idx_resume_analyses_resume_created ON careerprep.resume_analyses (resume_id, created_at DESC);
CREATE INDEX idx_job_descriptions_user_created ON careerprep.job_descriptions (user_id, created_at DESC);
CREATE INDEX idx_job_matches_user_created ON careerprep.job_matches (user_id, created_at DESC);
CREATE INDEX idx_job_matches_resume ON careerprep.job_matches (resume_id);
CREATE INDEX idx_job_matches_job ON careerprep.job_matches (job_description_id);
CREATE INDEX idx_interview_sessions_user_created ON careerprep.interview_sessions (user_id, created_at DESC);
CREATE INDEX idx_interview_sessions_resume ON careerprep.interview_sessions (resume_id);
CREATE INDEX idx_interview_sessions_job ON careerprep.interview_sessions (job_description_id);
-- uq_interview_questions_number supports session + question ordering.
-- uq interview_answers.interview_question_id supports answer lookup.

CREATE FUNCTION careerprep.touch_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_users_touch BEFORE UPDATE ON careerprep.users
    FOR EACH ROW EXECUTE FUNCTION careerprep.touch_updated_at();
CREATE TRIGGER trg_resumes_touch BEFORE UPDATE ON careerprep.resumes
    FOR EACH ROW EXECUTE FUNCTION careerprep.touch_updated_at();
CREATE TRIGGER trg_resume_analyses_touch BEFORE UPDATE ON careerprep.resume_analyses
    FOR EACH ROW EXECUTE FUNCTION careerprep.touch_updated_at();
CREATE TRIGGER trg_job_descriptions_touch BEFORE UPDATE ON careerprep.job_descriptions
    FOR EACH ROW EXECUTE FUNCTION careerprep.touch_updated_at();
CREATE TRIGGER trg_job_matches_touch BEFORE UPDATE ON careerprep.job_matches
    FOR EACH ROW EXECUTE FUNCTION careerprep.touch_updated_at();
CREATE TRIGGER trg_interview_sessions_touch BEFORE UPDATE ON careerprep.interview_sessions
    FOR EACH ROW EXECUTE FUNCTION careerprep.touch_updated_at();
CREATE TRIGGER trg_interview_answers_touch BEFORE UPDATE ON careerprep.interview_answers
    FOR EACH ROW EXECUTE FUNCTION careerprep.touch_updated_at();

-- A private schema is deliberately NOT accessible with Supabase's anon/authenticated keys.
-- Do NOT expose 'careerprep' in Supabase Data API settings.
REVOKE ALL ON ALL TABLES IN SCHEMA careerprep FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA careerprep FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA careerprep FROM PUBLIC, anon, authenticated;

COMMIT;
